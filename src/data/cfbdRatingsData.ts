export function getSPPlusRating(teamName: string): SPPlusTeamRating | undefined {
  if (CFBD_FBS_RATINGS[teamName]) return CFBD_FBS_RATINGS[teamName];
  const lower = teamName.toLowerCase().trim();
  for (const [name, rating] of Object.entries(CFBD_FBS_RATINGS)) {
    if (name.toLowerCase() === lower || lower.includes(name.toLowerCase()) || name.toLowerCase().includes(lower)) {
      return rating;
    }
  }
  return undefined;
}
